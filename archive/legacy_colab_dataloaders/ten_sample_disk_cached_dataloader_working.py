class FastDiskCachedZStackDataset(Dataset):
    """Z-Stack dataset with parallel disk caching"""
    def __init__(self, root_dir, w_count, cache_dir="/content/cache/zstack"):
        self.root_dir = Path(root_dir)
        self.cache_dir = Path(cache_dir)
        self.cache_dir.mkdir(parents=True, exist_ok=True)
        self.w_count = w_count

        # Scan directory structure
        self.samples = []
        for i in range(1, self.w_count + 1):
            w_id = f"W{i:03d}"
            p_folder = self.root_dir / w_id / "P00001"

            if not p_folder.exists():
                continue

            tif_files = sorted([
                p for p in p_folder.iterdir()
                if p.is_file() and p.suffix.lower() == ".tif"
            ])

            if len(tif_files) > 0:
                self.samples.append((w_id, tif_files))

        print(f"  Found {len(self.samples)} z-stack samples")

    def parallel_precache(self, max_workers=8):
        """Precache all data in parallel"""
        print(f"  Precaching {len(self.samples)} z-stacks with {max_workers} workers...")

        tasks = []
        for well_id, tif_files in self.samples:
            cache_path = self.cache_dir / f"{well_id}.npy"
            tasks.append((well_id, tif_files, cache_path))

        cached_count = 0
        loaded_count = 0

        with ThreadPoolExecutor(max_workers=max_workers) as executor:
            futures = {
                executor.submit(load_single_zstack, w_id, tifs, cp): w_id
                for w_id, tifs, cp in tasks
            }

            with tqdm(total=len(tasks), desc="  Z-stacks") as pbar:
                for future in as_completed(futures):
                    well_id, status = future.result()
                    if status == "cached":
                        cached_count += 1
                    else:
                        loaded_count += 1
                    pbar.update(1)

        print(f"  ✓ Complete: {cached_count} already cached, {loaded_count} newly loaded")

    def __len__(self):
        return len(self.samples)

    def __getitem__(self, idx):
        well_id, _ = self.samples[idx]
        cache_path = self.cache_dir / f"{well_id}.npy"

        if not cache_path.exists():
            raise RuntimeError(f"Cache missing for {well_id}. Run parallel_precache() first!")

        z_stack = np.load(cache_path)
        return (z_stack, well_id)

class FastDiskCachedFocusStackDataset(Dataset):
    """Focus-stacked dataset with parallel disk caching"""
    def __init__(self, root_dir, cache_dir="/content/cache/focus", target_size=(1440, 1920)):
        self.root_dir = Path(root_dir)
        self.cache_dir = Path(cache_dir)
        self.cache_dir.mkdir(parents=True, exist_ok=True)
        self.target_size = target_size

        # Find all focus_stacked.tif files
        self.samples = []
        for p in self.root_dir.rglob("*"):
            if p.is_file() and p.suffix.lower() == ".tif" and p.name.lower().endswith("focus_stacked.tif"):
                self.samples.append(p)

        self.samples = sorted(self.samples)
        print(f"  Found {len(self.samples)} focus-stack samples")

    def parallel_precache(self, max_workers=8):
        """Precache all data in parallel"""
        print(f"  Precaching {len(self.samples)} focus-stacks with {max_workers} workers...")

        import re
        tasks = []
        for file_path in self.samples:
            match = re.search(r'(W\d{3})', str(file_path))
            if match:
                well_id = match.group(1)
                cache_path = self.cache_dir / f"{well_id}.npy"
                tasks.append((well_id, file_path, cache_path))

        cached_count = 0
        loaded_count = 0

        with ThreadPoolExecutor(max_workers=max_workers) as executor:
            futures = {
                executor.submit(load_single_focus, w_id, fp, cp, self.target_size): w_id
                for w_id, fp, cp in tasks
            }

            with tqdm(total=len(tasks), desc="  Focus") as pbar:
                for future in as_completed(futures):
                    well_id, status = future.result()
                    if status == "cached":
                        cached_count += 1
                    else:
                        loaded_count += 1
                    pbar.update(1)

        print(f"  ✓ Complete: {cached_count} already cached, {loaded_count} newly loaded")

    def __len__(self):
        return len(self.samples)

    def __getitem__(self, idx):
        import re
        file_path = self.samples[idx]
        match = re.search(r'(W\d{3})', str(file_path))
        if match:
            well_id = match.group(1)
        else:
            raise ValueError(f"Could not extract well ID from: {file_path}")

        cache_path = self.cache_dir / f"{well_id}.npy"

        if not cache_path.exists():
            raise RuntimeError(f"Cache missing for {well_id}. Run parallel_precache() first!")

        img = np.load(cache_path)
        return (img, well_id)

