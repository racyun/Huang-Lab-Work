class JoinedDataset(Dataset):
    """Combines z-stack, focus, and hybrid images with labels"""
    def __init__(self, zstack_ds, focus_ds, hybrid_ds, labels_dir, kpa):
        self.zstack_ds = zstack_ds
        self.focus_ds = focus_ds
        self.hybrid_ds = hybrid_ds
        self.labels_dir = Path(labels_dir)
        self.kpa = float(kpa)

        assert len(zstack_ds) == len(focus_ds) == len(hybrid_ds), \
            "All component datasets must have the same length"

    def __len__(self):
        return len(self.focus_ds)

    def __getitem__(self, idx):
        z_stack, z_well_id = self.zstack_ds[idx]
        focus_img, f_well_id = self.focus_ds[idx]
        hybrid_img, h_well_id = self.hybrid_ds[idx]

        assert z_well_id == f_well_id == h_well_id, \
            f"Well ID mismatch: {z_well_id}, {f_well_id}, {h_well_id}"

        well_id = z_well_id

        label_path = str(self.labels_dir / f"{well_id}.txt")
        bboxes = load_txt_cached(label_path)

        kpa_tensor = torch.tensor([self.kpa], dtype=torch.float32)

        return {
            'z_stack': z_stack,
            'focus': focus_img,
            'hybrid': hybrid_img,
            'bboxes': bboxes,
            'kpa': kpa_tensor,
            'well_id': well_id
        }

