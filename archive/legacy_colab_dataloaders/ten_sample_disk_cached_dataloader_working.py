def custom_collate_fn(batch):
    """Custom collate to handle variable-length bboxes"""
    z_stacks = torch.stack([torch.from_numpy(item['z_stack']).float() for item in batch])
    focus_imgs = torch.stack([torch.from_numpy(item['focus']).float() for item in batch])
    hybrid_imgs = torch.stack([torch.from_numpy(item['hybrid']).float() for item in batch])
    kpas = torch.stack([item['kpa'] for item in batch])

    bboxes = [item['bboxes'] for item in batch]
    well_ids = [item['well_id'] for item in batch]

    return {
        'z_stack': z_stacks,
        'focus': focus_imgs,
        'hybrid': hybrid_imgs,
        'bboxes': bboxes,
        'kpa': kpas,
        'well_ids': well_ids
    }

