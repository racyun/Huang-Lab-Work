def create_fast_dataloader(
    zstack_root_900kpa,
    zstack_root_5kpa,
    focus_root_900kpa,
    focus_root_5kpa,
    hybrid_root_900kpa,
    hybrid_root_5kpa,
    labels_900kpa,
    labels_5kpa,
    cache_base_dir="/content/cache",
    batch_size=4,
    num_workers=0,
    shuffle=True,
    max_workers=16,  # Parallel loading threads
    w_count=10
):
    """
    Create fast dataloader with parallel caching

    Args:
        max_workers: Number of parallel threads for caching (default: 16)
                     Higher = faster, but don't go crazy (16-32 is good)
    """

    print("\n" + "=" * 70)
    print("  CREATING FAST PARALLEL-CACHED DATALOADER")
    print("=" * 70 + "\n")

    # Create datasets
    print("Creating 900kPa datasets...")
    zstack_900 = FastDiskCachedZStackDataset(
        zstack_root_900kpa,
        w_count=w_count,
        cache_dir=f"{cache_base_dir}/zstack_900"
    )
    focus_900 = FastDiskCachedFocusStackDataset(
        focus_root_900kpa,
        cache_dir=f"{cache_base_dir}/focus_900",
        target_size=(1440, 1920)
    )
    hybrid_900 = FastDiskCachedHybridDataset(
        hybrid_root_900kpa,
        w_count=w_count,
        cache_dir=f"{cache_base_dir}/hybrid_900"
    )

    print("\nCreating 5kPa datasets...")
    zstack_5 = FastDiskCachedZStackDataset(
        zstack_root_5kpa,
        w_count=w_count,
        cache_dir=f"{cache_base_dir}/zstack_5"
    )
    focus_5 = FastDiskCachedFocusStackDataset(
        focus_root_5kpa,
        cache_dir=f"{cache_base_dir}/focus_5",
        target_size=(1440, 1920)
    )
    hybrid_5 = FastDiskCachedHybridDataset(
        hybrid_root_5kpa,
        w_count=w_count,
        cache_dir=f"{cache_base_dir}/hybrid_5"
    )

    # Parallel precache all data
    print("\n" + "=" * 70)
    print("  PRECACHING ALL DATA IN PARALLEL")
    print(f"  Using {max_workers} parallel workers")
    print("=" * 70 + "\n")

    total_start = time.time()

    print("900kPa datasets:")
    zstack_900.parallel_precache(max_workers=max_workers)
    focus_900.parallel_precache(max_workers=max_workers)
    hybrid_900.parallel_precache(max_workers=max_workers)

    print("\n5kPa datasets:")
    zstack_5.parallel_precache(max_workers=max_workers)
    focus_5.parallel_precache(max_workers=max_workers)
    hybrid_5.parallel_precache(max_workers=max_workers)

    total_time = time.time() - total_start

    print("\n" + "=" * 70)
    print(f"  ALL DATA CACHED in {total_time/60:.1f} minutes!")
    print("=" * 70 + "\n")

    # Create joined datasets
    print("Joining datasets with labels...")
    dataset_900 = JoinedDataset(zstack_900, focus_900, hybrid_900, labels_900kpa, kpa=900)
    dataset_5 = JoinedDataset(zstack_5, focus_5, hybrid_5, labels_5kpa, kpa=5)

    full_dataset = ConcatDataset([dataset_900, dataset_5])
    print(f"Total samples in dataset: {len(full_dataset)}")

    # Create dataloader
    print(f"\nCreating DataLoader (batch_size={batch_size}, num_workers={num_workers})...")
    loader = DataLoader(
        full_dataset,
        batch_size=batch_size,
        shuffle=shuffle,
        num_workers=num_workers,
        collate_fn=custom_collate_fn,
        pin_memory=True
    )

    print("✓ DataLoader ready!\n")

    return loader, full_dataset

