@lru_cache(maxsize=500)
def load_txt_cached(txt_path):
    """Load and cache bounding box labels"""
    with open(txt_path, 'r') as f:
        lines = [line.strip() for line in f if line.strip()]

    bboxes = []
    for line in lines:
        coords = [float(x) for x in line.split(',')]
        bboxes.append(coords)

    return torch.tensor(bboxes, dtype=torch.float32) if bboxes else torch.zeros((0, 4))

