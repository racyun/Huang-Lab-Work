def load_single_zstack(well_id, tif_files, cache_path):
    """Load a single z-stack in parallel"""
    if cache_path.exists():
        return well_id, "cached"

    images = []
    for tif_path in tif_files:
        img = Image.open(tif_path)
        images.append(np.array(img))

    z_stack = np.stack(images, axis=0)
    np.save(cache_path, z_stack)

    return well_id, "loaded"


def load_single_focus(well_id, file_path, cache_path, target_size=(1440, 1920)):
    """Load a single focus image in parallel"""
    if cache_path.exists():
        return well_id, "cached"

    img_pil = Image.open(file_path)
    if target_size:
        img_pil = img_pil.resize((target_size[1], target_size[0]), Image.BILINEAR)

    img = np.array(img_pil)
    np.save(cache_path, img)

    return well_id, "loaded"


def load_single_hybrid(well_id, tif_path, cache_path):
    """Load a single hybrid image in parallel"""
    if cache_path.exists():
        return well_id, "cached"

    img = np.array(Image.open(tif_path))
    np.save(cache_path, img)

    return well_id, "loaded"

