class DriveImageDataset(Dataset):
    def __init__(self, root_dir, transform=None, recursive=True):
        self.root_dir = Path(root_dir)
        self.transform = transform

        # Choose how to iterate:
        # - recursive=True  -> searches all subfolders too
        # - recursive=False -> only looks at files directly inside ROOT
        iterator = self.root_dir.rglob("*") if recursive else self.root_dir.iterdir()

