import re
from pathlib import Path
import torch
from torch.utils.data import Dataset, DataLoader

W_RE = re.compile(r"(W\d{3})")

def get_well_id_from_anything(x):
    """
    Try to extract W### from a path/string or dict.
    Adjust based on what your dataset returns.
    """
    if isinstance(x, dict):
        # common keys that might contain the filepath or id
        for k in ["path", "filepath", "file", "fname", "id", "name"]:
            if k in x and x[k] is not None:
                m = W_RE.search(str(x[k]))
                if m: return m.group(1)
    m = W_RE.search(str(x))
    if not m:
        raise ValueError(f"Could not find W### in: {x}")
    return m.group(1)

def load_txt(txt_path: Path):
    rows = []
    with open(txt_path, "r") as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            # Expect: "x1,y1,x2,y2" (possibly with spaces)
            parts = [p.strip() for p in line.split(",")]
            if len(parts) != 4:
                raise ValueError(f"Expected 4 comma-separated numbers in {txt_path.name}, got: {line}")
            rows.append([float(p) for p in parts])
    # shape [N, 4]; if no boxes, return [0,4] tensor
    return torch.tensor(rows, dtype=torch.float32) if rows else torch.zeros((0, 4), dtype=torch.float32)


class JoinTwoDatasetsWithTxt(Dataset):
    def __init__(self, zstack_ds, focus_ds, hybrid_ds, labels_dir, kpa, id_getter=None):
        self.zstack_ds = zstack_ds
        self.focus_ds = focus_ds
        self.hybrid_ds = hybrid_ds
        self.labels_dir = Path(labels_dir)
        self.id_getter = id_getter or get_well_id_from_anything
        self.kpa = float(kpa)

    def __len__(self):
        return len(self.focus_ds)

    def __getitem__(self, idx):
        a = self.zstack_ds[idx]
        b = self.focus_ds[idx]
        c = self.hybrid_ds[idx]

        wid = self.id_getter(b[1])
        y_path = self.labels_dir / f"{wid}.txt"
        y = load_txt(y_path)

        # return kpa as a real model input feature (tensor)
        kpa = torch.tensor([self.kpa], dtype=torch.float32)  # shape [1]
        return a, b, c, y, kpa


def collate_join(batch):
    a_list, b_list, c_list, y_list, kpa_list = zip(*batch)

    a_imgs  = torch.stack([a[0] for a in a_list])
    a_paths = [a[1] for a in a_list]

    b_imgs  = torch.stack([b[0] for b in b_list])
    b_paths = [b[1] for b in b_list]

    c_imgs  = torch.stack([c[0] for c in c_list])
    c_paths = [c[1] for c in c_list]

    y = list(y_list)                 # list of [Ni,4]
    kpa = torch.stack(kpa_list)      # [B, 1]

    return {
        "zstack": a_imgs,
        "focus": b_imgs,
        "hybrid": c_imgs,
        "y": y,
        "kpa": kpa,
        "zstack_paths": a_paths,
        "focus_paths": b_paths,
        "hybrid_paths": c_paths,
    }


