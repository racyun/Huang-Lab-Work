class ZStackWithLabelDataset(Dataset):
    """
    One sample per W-folder:
      x: 140 tif images from ROOT/Wxxx/P00001/*.tif  -> returned as tensor [Z, C, H, W]
      y: label text from LABEL_DIR/Wxxx.txt
    """
    def __init__(self, root_dir, label_dir, transform=None, w_prefix="W", w_count=222, p_folder="P00001"):
        self.root_dir = Path(root_dir)
        self.label_dir = Path(label_dir)
        self.transform = transform

        self.samples = []  # list of dicts: {"w_id": "W001", "img_paths": [...], "label_path": Path(...)}

        for i in range(1, w_count + 1):
            w_id = f"{w_prefix}{i:03d}"  # W001..W222

            p_dir = self.root_dir / w_id / p_folder
            label_path = self.label_dir / f"{w_id}.txt"

            if not p_dir.exists():
                print(f"[WARN] Missing image folder: {p_dir}")
                continue

            img_paths = sorted([
                p for p in p_dir.iterdir()
                if p.is_file() and p.suffix.lower() in IMG_EXTS
            ])

            if len(img_paths) == 0:
                print(f"[WARN] No .tif files found in: {p_dir}")
                continue

            if not label_path.exists():
                print(f"[WARN] Missing label file: {label_path}")
                continue

            self.samples.append({
                "w_id": w_id,
                "img_paths": img_paths,
                "label_path": label_path
            })

        if len(self.samples) == 0:
            raise ValueError("No valid (z-stack, label) pairs found. Check ROOT and LABEL_DIR.")

        print(f"\nTotal samples (W folders) loaded: {len(self.samples)}")

    def __len__(self):
        return len(self.samples)

    def __getitem__(self, idx):
        sample = self.samples[idx]
        w_id = sample["w_id"]
        img_paths = sample["img_paths"]
        label_path = sample["label_path"]

        # Load stack: list of [C,H,W] -> tensor [Z,C,H,W]
        slices = []
        for p in img_paths:
            with Image.open(p) as im:
                im = im.convert("RGB")
            if self.transform:
                im = self.transform(im)  # [C,H,W]
            else:
                im = transforms.ToTensor()(im)
            slices.append(im)

        stack = torch.stack(slices, dim=0)  # [Z, C, H, W]

        # Read label text (keep as raw text for now; parse later if needed)
        label_text = label_path.read_text()

        return stack, label_text, w_id


